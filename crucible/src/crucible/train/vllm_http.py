"""A vLLM OpenAI-compatible server as an M12 engine (the real-model inference side).

Token-in-token-out: ``/v1/completions`` with a token-id ``prompt``, ``return_token_ids`` and ``logprobs=0`` (the sampled
token's logprob; vLLM ``--logprobs-mode processed_logprobs`` makes it the post-temperature value the trainer recomputes).
Versions are ours: the engine's ``version`` changes only through ``load_weights``, and every response is stamped with
the version that was serving when the call started (call-level switching: a call cut by ``abort_all``/``pause`` returns
``finish="abort"`` and is re-issued whole by the runtime, or resumed from its kept tokens under ``version_switch="token"``).
A publish while serving pauses the server with abort first; a request that overlapped a weight swap is always returned
as an abort, so no response is stamped with a version it was not entirely generated by.

Lifecycle on one GPU (research m11-m12/03 finding 1): the server keeps a fixed memory fraction. In ``colocated``
placement ``pause()`` also puts it to ``/sleep?level=1`` (weights to CPU, KV discarded) so the trainer gets the memory;
``load_weights`` wakes **only the weights**, loads the published checkpoint through ``/collective_rpc`` →
``CrucibleWorkerExtension.crucible_load_weights`` and resets the prefix cache (a cache from old weights is stale);
``resume()`` wakes the KV cache and reopens generation. The KV cache must not wake inside the publish: the runtime offloads
the trainer *between* publish and resume, and waking the KV first would put the full trainer and the full engine on the
GPU at once (m13 audit 04: the wake-order defect that defeated sleep mode). In ``split`` placement it never sleeps (memory split: disaggregated
semantics on one device).

Requires the server started with ``VLLM_SERVER_DEV_MODE=1 --enable-sleep-mode --worker-extension-cls
crucible_vllm_ext.CrucibleWorkerExtension`` (and ``--logprobs-mode processed_logprobs``).
"""

from __future__ import annotations

import asyncio
import uuid
from typing import Any

import httpx

from crucible.train.engine import GenRequest, GenResult, resume_spans


class VLLMServerEngine:
    def __init__(self, base_url: str, model: str, *, capacity: int = 64, placement: str = "colocated", timeout_s: float = 1800.0, sleep_level: int = 1,
                 nucleus_k: int = 0, api_key: str | None = None):
        """``nucleus_k`` > 0 (m13 F-4): top-p sampling is allowed; each position's nucleus is rebuilt from the top-``k``
        processed logprobs (``return_tokens_as_token_ids``), exact whenever the top-``k`` mass reaches ``top_p``; a position
        where it does not (or the sampled token is outside it) fails the call, never a guessed candidate set. Run the
        server with ``--logprobs-mode processed_logprobs`` so the probabilities are the sampled distribution's."""
        self.base, self.model, self.capacity, self.placement, self.sleep_level = base_url.rstrip("/"), model, capacity, placement, sleep_level
        self.nucleus_k = nucleus_k
        self.version = 0
        # ``api_key``: a server started with ``--api-key`` (a cloud endpoint, e.g. scripts/modal_vllm.py) wants a bearer token
        self.client = httpx.AsyncClient(timeout=timeout_s, headers={"Authorization": f"Bearer {api_key}"} if api_key else None)
        self._unpaused = asyncio.Event()
        self._unpaused.set()
        self._tasks: dict[str, asyncio.Task] = {}
        self._weights_epoch = 0  # moves at every weight swap: a request that overlapped one is returned as an abort
        self.asleep: set[str] = set()  # sleeping vLLM memory tags: "weights", "kv_cache"

    async def _post(self, path: str, json: Any = None, params: Any = None) -> httpx.Response:
        r = await self.client.post(self.base + path, json=json, params=params)
        r.raise_for_status()
        return r

    kv_modes = ("discard",)  # vLLM sleep discards the KV cache; keeping it in a host pool needs a KV-offload connector

    def capabilities(self) -> dict[str, Any]:
        """vLLM reports *raw* logprobs unless the server runs with ``--logprobs-mode processed_logprobs`` (check with
        ``hf_engine.probe_logprobs_mode``); top-p candidate sets are rebuilt with ``nucleus_k``; routed experts are not
        exposed over HTTP. ``pause`` aborts running requests (``/pause?mode=abort``); ``token_resume``: a call resumes from
        its kept output (``GenRequest.resume_completion``) as a new request with the kept tokens appended to the prompt."""
        return {"token_ids": True, "logprobs": "server", "abort": "all", "pause": ["abort"], "sleep": self.placement == "colocated",
                "top_p_candidates": self.nucleus_k > 0, "routing": False, "weight_load": "checkpoint_dir", "token_resume": True}

    async def generate(self, req: GenRequest) -> GenResult:
        nucleus = req.top_p < 1.0
        if nucleus and not self.nucleus_k:  # checklist #37: without the per-token nucleus the trainer would compare against the wrong distribution
            raise NotImplementedError("top-p sampling needs VLLMServerEngine(nucleus_k=K) to rebuild candidate sets; or sample with top_p=1.0")
        await self._unpaused.wait()
        version, epoch = self.version, self._weights_epoch
        kept, kept_lps, kept_c = list(req.resume_completion), list(req.resume_logprobs), list(req.resume_candidates)

        def done(new: list[int], new_lps: list[float], new_c: list[list[int]] | None, finish: str) -> GenResult:
            spans = resume_spans(req.resume_spans, len(kept), len(new), version)
            cands = (kept_c + list(new_c or [])) if (nucleus or kept_c) else None
            sp = spans if (finish == "abort" and kept) or len(spans) > 1 else None
            return GenResult(kept + list(new), kept_lps + [float(x) for x in new_lps], spans[-1][1], finish, sp, len(req.prompt_ids), cands or None)

        left = req.max_tokens - len(kept)
        if left <= 0:
            return done([], [], [], "length")
        rid = f"{req.call_id}-{uuid.uuid4().hex[:6]}"
        # token-level resume (G3 D8: the kept output was silently dropped while the runtime counted a token resume): the kept
        # tokens extend the prompt, so the new request continues exactly where the aborted one stopped
        body = {"model": self.model, "prompt": list(req.prompt_ids) + kept, "max_tokens": left, "temperature": req.temperature,
                "logprobs": self.nucleus_k if nucleus else 0, "return_token_ids": True, "skip_special_tokens": False,
                "stop_token_ids": list(req.stop_ids) or None, "seed": req.seed, "request_id": rid,
                **({"top_p": req.top_p, "return_tokens_as_token_ids": True} if nucleus else {})}
        task = asyncio.create_task(self.client.post(self.base + "/v1/completions", json={k: v for k, v in body.items() if v is not None},
                                                    headers={"X-Request-Id": rid}))
        self._tasks[rid] = task
        try:
            r = await task
        except asyncio.CancelledError:
            if task.cancelled():
                return done([], [], [], "abort")  # the kept output survives a cancelled resume
            raise
        finally:
            self._tasks.pop(rid, None)
        if self._weights_epoch != epoch:
            # the weights were swapped while this request ran: its tokens may come from two weight sets, and vLLM does not
            # say where the boundary is. Discarded and re-issued, never stamped with a version it was not fully generated
            # with (M12 audit V2: [old x4, new x6] came back stamped with the old version)
            return done([], [], [], "abort")
        if r.status_code == 400 and any(k in r.text.lower() for k in ("maximum context length", "context length", "too long", "max_model_len",
                                                                          "maximum model length")):
            # the prompt plus max_tokens exceeds the engine's model length: a "length" finish with no tokens, which
            # ``EngineLLM`` raises as ContextOverflow, so the policy's episode ends context_overflow, truncated (M2 R-1: it
            # was read as an empty reply and ended agent_done); found live: it crashed a backlog run's driver as an HTTP error
            return done([], [], [], "length")
        if r.status_code >= 400:
            raise RuntimeError(f"vLLM {r.status_code} on /v1/completions: {r.text[:600]}")  # the server's reason, not just the status
        ch = r.json()["choices"][0]
        ids = list(ch.get("token_ids") or [])
        lps = list(((ch.get("logprobs") or {}).get("token_logprobs")) or [])
        if len(lps) != len(ids):
            raise RuntimeError(f"vLLM returned {len(lps)} logprobs for {len(ids)} tokens (is logprobs requested?)")
        if ch.get("finish_reason") == "abort":
            # aborted by ``pause`` / ``abort_all`` before any swap (the epoch did not move): every token is this version's
            return done(ids, lps, _nuclei(ids, (ch.get("logprobs") or {}).get("top_logprobs") or [], req.top_p) if nucleus and ids else None, "abort")
        cands = _nuclei(ids, (ch.get("logprobs") or {}).get("top_logprobs") or [], req.top_p) if nucleus else None
        return done(ids, lps, cands, "stop" if ch.get("finish_reason") == "stop" else "length")

    async def abort_all(self) -> int:
        """Cancel every request in flight (vLLM aborts a request whose client disconnects), then ask the server too.
        ``/abort_requests`` is not part of every vLLM build: a 404 / 405 there is not an engine failure (M12 audit V19:
        it raised after the cancels, and the gateway evicted every engine at each barrier)."""
        n = len(self._tasks)
        for t in list(self._tasks.values()):
            t.cancel()
        try:
            await self._post("/abort_requests", json={})
        except httpx.HTTPStatusError as e:
            if e.response.status_code not in (404, 405):
                raise
        return n

    @property
    def sleeping(self) -> bool:
        return bool(self.asleep)

    async def pause(self) -> None:
        self._unpaused.clear()
        await self._post("/pause", params={"mode": "abort"})
        if self.placement == "colocated":
            await self._post("/sleep", params={"level": str(self.sleep_level)})
            self.asleep = {"weights", "kv_cache"}

    async def _wake(self, tag: str) -> None:
        if tag in self.asleep:
            await self._post("/wake_up", params=[("tags", tag)])
            self.asleep.discard(tag)

    async def resume(self) -> None:
        await self._wake("weights")  # (a resume without a publish)
        await self._wake("kv_cache")  # only now: the trainer has been offloaded by the runtime
        await self._post("/resume")
        self._unpaused.set()

    async def load_weights(self, path: str, version: int) -> None:
        """Load a published checkpoint. While the engine serves (``disaggregated_stream``, the resident group of
        ``elastic``) new calls wait, running requests are aborted (``/pause?mode=abort``) and re-issued on the new
        weights after the swap, the SkyRL order (pause before every weight sync): vLLM applies ``/collective_rpc``
        between engine steps, so a running request would otherwise decode on two weight sets under one version stamp
        (M12 audit V2). Any call whose request overlapped the swap is returned as an abort (``_weights_epoch``)."""
        serving = self._unpaused.is_set()
        self._unpaused.clear()
        paused = False
        try:
            self._weights_epoch += 1
            if serving and self._tasks:
                await self._post("/pause", params={"mode": "abort"})
                paused = True
            await self._wake("weights")
            await self._post("/collective_rpc", json={"method": "crucible_load_weights", "args": [str(path)]})
            await self._post("/reset_prefix_cache")
            self.version = version
            self._weights_epoch += 1
        finally:
            if paused:
                await self._post("/resume")
            if serving:
                self._unpaused.set()


NEG_FLOOR = -9998.0  # vLLM serializes a -inf logprob as -9999.0 (OpenAI-compatible floor)


def _nuclei(ids: list[int], top: list[dict], top_p: float) -> list[list[int]]:
    """Per position, the top-p nucleus read from vLLM's top-k **processed** logprobs (keys ``token_id:<id>``). Processed
    logprobs are taken after top-k/top-p filtering and renormalized over the kept set: tokens outside the nucleus are -inf
    (serialized -9999). So the nucleus is exactly the finite entries, and it is known complete when the top-k list reaches
    a filtered (-inf) entry or the finite mass sums to 1. M12 audit: summing these renormalized probabilities up to
    ``top_p`` stopped early and rebuilt too small a set (true {0, 1, 2}, rebuilt {0, 1}). An incomplete nucleus, or a
    sampled token outside it, fails the call: a guessed candidate set would make the trainer renormalize over the wrong
    distribution. Raw logprobs (a server without ``--logprobs-mode processed_logprobs``) never sum to 1 and fail here."""
    import math

    if len(top) != len(ids):
        raise ValueError(f"vLLM returned top logprobs for {len(top)} of {len(ids)} positions")
    out = []
    for i, (tok, pos) in enumerate(zip(ids, top, strict=True)):
        items = [(int(str(k).removeprefix("token_id:")), float(v)) for k, v in (pos or {}).items()]
        nuc = [t for t, v in items if math.isfinite(v) and v > NEG_FLOOR]
        mass = sum(math.exp(v) for t, v in items if math.isfinite(v) and v > NEG_FLOOR)
        complete = len(nuc) < len(items) or mass >= 1.0 - 1e-4
        if not complete:
            raise ValueError(f"position {i}: the top-{len(items)} processed candidates hold {mass:.3f} of the renormalized nucleus and none "
                             f"was filtered; raise nucleus_k (or the server returns raw logprobs: run --logprobs-mode processed_logprobs)")
        if tok not in nuc:
            raise ValueError(f"position {i}: sampled token {tok} is outside the nucleus (is the server returning processed logprobs?)")
        out.append(sorted(nuc))
    return out
